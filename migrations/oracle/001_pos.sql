CREATE TABLE users (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR2(50 CHAR) NOT NULL,
  password_hash VARCHAR2(100 CHAR) NOT NULL,
  role VARCHAR2(10 CHAR) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_users_role CHECK (role IN ('cashier', 'admin'))
);
CREATE UNIQUE INDEX ux_users_username ON users (UPPER(username));

CREATE TABLE customers (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR2(200 CHAR) NOT NULL,
  phone VARCHAR2(50 CHAR),
  debt_amount NUMBER(15,0) DEFAULT 0 NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_customers_debt CHECK (debt_amount >= 0)
);
CREATE INDEX ix_customers_name ON customers (UPPER(name));
CREATE INDEX ix_customers_phone ON customers (phone);

CREATE TABLE products (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR2(200 CHAR) NOT NULL,
  sku VARCHAR2(100 CHAR),
  purchase_price NUMBER(15,0) DEFAULT 0 NOT NULL,
  retail_price NUMBER(15,0) DEFAULT 0 NOT NULL,
  stock_quantity NUMBER(14,3) DEFAULT 0 NOT NULL,
  low_stock_threshold NUMBER(14,3) DEFAULT 5 NOT NULL,
  size_label VARCHAR2(100 CHAR),
  unit VARCHAR2(3 CHAR) DEFAULT 'pcs' NOT NULL,
  category VARCHAR2(100 CHAR) DEFAULT 'Общая' NOT NULL,
  image_url VARCHAR2(2000 CHAR),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_products_purchase CHECK (purchase_price >= 0),
  CONSTRAINT ck_products_retail CHECK (retail_price >= 0),
  CONSTRAINT ck_products_stock CHECK (stock_quantity >= 0),
  CONSTRAINT ck_products_low_stock CHECK (low_stock_threshold >= 0),
  CONSTRAINT ck_products_unit CHECK (unit IN ('pcs', 'm')),
  CONSTRAINT ck_products_category CHECK (LENGTH(TRIM(category)) BETWEEN 1 AND 100)
);
CREATE UNIQUE INDEX ux_products_sku ON products (UPPER(sku));
CREATE INDEX ix_products_name ON products (UPPER(name));
CREATE INDEX ix_products_category ON products (UPPER(category));

CREATE TABLE shifts (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cashier_id NUMBER NOT NULL REFERENCES users(id),
  opened_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  closed_at TIMESTAMP WITH TIME ZONE,
  revenue_cash NUMBER(15,0) DEFAULT 0 NOT NULL,
  revenue_card NUMBER(15,0) DEFAULT 0 NOT NULL,
  revenue_debt NUMBER(15,0) DEFAULT 0 NOT NULL,
  total_revenue NUMBER(15,0) DEFAULT 0 NOT NULL,
  net_profit NUMBER(15,0) DEFAULT 0 NOT NULL
);
CREATE INDEX ix_shifts_cashier_open ON shifts (cashier_id, closed_at);

CREATE TABLE sales (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cashier_id NUMBER NOT NULL REFERENCES users(id),
  shift_id NUMBER REFERENCES shifts(id),
  customer_id NUMBER REFERENCES customers(id) ON DELETE SET NULL,
  total_amount NUMBER(15,0) NOT NULL,
  payment_type VARCHAR2(10 CHAR) NOT NULL,
  cash_received NUMBER(15,0) DEFAULT 0 NOT NULL,
  change_amount NUMBER(15,0) DEFAULT 0 NOT NULL,
  subtotal_amount NUMBER(15,0) DEFAULT 0 NOT NULL,
  discount_amount NUMBER(15,0) DEFAULT 0 NOT NULL,
  discount_reason VARCHAR2(200 CHAR),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_sales_amount CHECK (total_amount >= 0 AND cash_received >= 0 AND change_amount >= 0),
  CONSTRAINT ck_sales_payment CHECK (payment_type IN ('cash', 'card', 'debt')),
  CONSTRAINT ck_sales_discount CHECK (subtotal_amount >= total_amount AND discount_amount = subtotal_amount - total_amount)
);
CREATE INDEX ix_sales_created ON sales (created_at);
CREATE INDEX ix_sales_cashier_created ON sales (cashier_id, created_at);
CREATE INDEX ix_sales_shift ON sales (shift_id);
CREATE INDEX ix_sales_customer ON sales (customer_id);

CREATE TABLE sale_items (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id NUMBER NOT NULL REFERENCES sales(id),
  product_id NUMBER REFERENCES products(id) ON DELETE SET NULL,
  product_name VARCHAR2(200 CHAR) NOT NULL,
  quantity NUMBER(14,3) NOT NULL,
  price_at_sale NUMBER(15,0) NOT NULL,
  cost_price_at_sale NUMBER(15,0) NOT NULL,
  CONSTRAINT ck_sale_items_values CHECK (quantity > 0 AND price_at_sale >= 0 AND cost_price_at_sale >= 0)
);
CREATE INDEX ix_sale_items_sale ON sale_items (sale_id);
CREATE INDEX ix_sale_items_product ON sale_items (product_id);

CREATE TABLE debt_payments (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id NUMBER NOT NULL REFERENCES customers(id),
  cashier_id NUMBER NOT NULL REFERENCES users(id),
  shift_id NUMBER REFERENCES shifts(id),
  payment_type VARCHAR2(10 CHAR) NOT NULL,
  amount NUMBER(15,0) NOT NULL,
  cash_received NUMBER(15,0) DEFAULT 0 NOT NULL,
  change_amount NUMBER(15,0) DEFAULT 0 NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_debt_payment_type CHECK (payment_type IN ('cash', 'card')),
  CONSTRAINT ck_debt_payment_amount CHECK (amount > 0 AND cash_received >= 0 AND change_amount >= 0)
);
CREATE INDEX ix_debt_customer_created ON debt_payments (customer_id, created_at);
CREATE INDEX ix_debt_payments_shift ON debt_payments (shift_id);

CREATE TABLE warehouse_documents (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type VARCHAR2(12 CHAR) NOT NULL,
  status VARCHAR2(12 CHAR) DEFAULT 'draft' NOT NULL,
  supplier_name VARCHAR2(200 CHAR),
  comment_text VARCHAR2(2000 CHAR),
  created_by NUMBER NOT NULL REFERENCES users(id),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  completed_at TIMESTAMP WITH TIME ZONE,
  CONSTRAINT ck_warehouse_doc_type CHECK (type IN ('purchase', 'inventory')),
  CONSTRAINT ck_warehouse_doc_status CHECK (status IN ('draft', 'completed'))
);
CREATE INDEX ix_wh_doc_created ON warehouse_documents (created_at);
CREATE INDEX ix_wh_doc_type_status ON warehouse_documents (type, status);

CREATE TABLE warehouse_document_items (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id NUMBER NOT NULL REFERENCES warehouse_documents(id),
  product_id NUMBER REFERENCES products(id) ON DELETE SET NULL,
  product_name VARCHAR2(200 CHAR) NOT NULL,
  expected_quantity NUMBER(14,3),
  actual_quantity NUMBER(14,3) NOT NULL,
  purchase_price NUMBER(15,0),
  retail_price NUMBER(15,0),
  CONSTRAINT ck_wh_item_quantity CHECK (actual_quantity >= 0 AND (expected_quantity IS NULL OR expected_quantity >= 0))
);
CREATE INDEX ix_wh_items_document ON warehouse_document_items (document_id);

CREATE TABLE stock_history (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id NUMBER REFERENCES products(id) ON DELETE SET NULL,
  product_name VARCHAR2(200 CHAR) NOT NULL,
  user_id NUMBER REFERENCES users(id) ON DELETE SET NULL,
  type VARCHAR2(24 CHAR) NOT NULL,
  quantity_change NUMBER(14,3) NOT NULL,
  stock_before NUMBER(14,3) NOT NULL,
  stock_after NUMBER(14,3) NOT NULL,
  reference_id NUMBER,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_stock_history_type CHECK (type IN ('purchase', 'sale', 'inventory_adjustment', 'manual_correction')),
  CONSTRAINT ck_stock_history_equation CHECK (stock_before >= 0 AND stock_after >= 0 AND ABS(stock_after - stock_before - quantity_change) < 0.000001)
);
CREATE INDEX ix_stock_product_created ON stock_history (product_id, created_at);
CREATE INDEX ix_stock_reference ON stock_history (type, reference_id);
