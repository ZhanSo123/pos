require('dotenv').config();
const path = require('node:path');
const Database = require('better-sqlite3');
const db = require('./db');

const tableOrder = ['users', 'customers', 'products', 'shifts', 'sales', 'sale_items', 'debt_payments', 'warehouse_documents', 'warehouse_document_items', 'stock_history'];
const timestampColumns = new Set(['created_at', 'updated_at', 'opened_at', 'closed_at', 'completed_at']);
const oracleColumnName = { products: { size: 'size_label' }, warehouse_documents: { comment: 'comment_text' } };

async function main() {
  const sourcePath = path.resolve(process.cwd(), process.env.LEGACY_SQLITE_PATH || process.env.DATABASE_PATH || './data/pos.sqlite');
  const sqlite = new Database(sourcePath, { readonly: true, fileMustExist: true });
  try {
    await db.initialize();
    const counts = {};
    for (const table of tableOrder) counts[table] = sqlite.prepare(`SELECT COUNT(*) AS count FROM ${table}`).get().count;
    const total = Object.values(counts).reduce((sum, count) => sum + count, 0);
    if (!total) throw new Error('The SQLite source contains no POS records.');
    const alreadyHasData = await db.get(`SELECT COUNT(*) AS count FROM users`);
    if (alreadyHasData.count > 0) throw new Error('Oracle already contains users. Import is only allowed into an empty POS schema.');

    await db.transaction(async connection => {
      for (const table of tableOrder) {
        const rows = sqlite.prepare(`SELECT * FROM ${table}`).all();
        if (!rows.length) continue;
        for (const row of rows) {
          const sourceColumns = Object.keys(row);
          const columns = sourceColumns.map(column => oracleColumnName[table]?.[column] || column);
          const binds = {};
          sourceColumns.forEach((column, index) => {
            const targetColumn = columns[index];
            const value = row[column];
            binds[targetColumn] = timestampColumns.has(column) && value ? new Date(value).toISOString().replace('Z', '+00:00') : value;
          });
          const names = columns.join(', ');
          const values = sourceColumns.map((column, index) => timestampColumns.has(column)
            ? `TO_TIMESTAMP_TZ(:${columns[index]}, 'YYYY-MM-DD"T"HH24:MI:SS.FF3TZH:TZM')`
            : `:${columns[index]}`).join(', ');
          await db.execute(`INSERT INTO ${table} (${names}) VALUES (${values})`, binds, connection);
        }
      }
    });

    for (const table of tableOrder) {
      if (counts[table] > 0) await db.execute(`ALTER TABLE ${table} MODIFY id GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE)`);
      console.log(`Imported ${counts[table]} ${table} row(s).`);
    }
    console.log(`SQLite records imported into Oracle Database. Source: ${sourcePath}`);
  } finally {
    sqlite.close();
    await db.close();
  }
}

main().catch(error => { console.error(`SQLite to Oracle import failed: ${error.message}`); process.exitCode = 1; });
